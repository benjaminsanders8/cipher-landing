// Compiles the bot's brain (bot/*.md) into api/_knowledge.js so the serverless
// function can import it without filesystem reads. Run after editing any file
// in bot/:   node bot/build-knowledge.js
const fs = require('fs');
const path = require('path');

const read = (f) => fs.readFileSync(path.join(__dirname, f), 'utf8').trim();

const persona = read('persona.md');
const cipher = read('knowledge-cipher.md');
const econ = read('knowledge-econ.md');

const system = [
  persona,
  '',
  '=== CIPHER KNOWLEDGE ===',
  cipher,
  '',
  '=== RESEARCH LIBRARY (your only source for research claims) ===',
  econ,
].join('\n');

const out = `// GENERATED by bot/build-knowledge.js — do not edit by hand.
// Edit bot/persona.md, bot/knowledge-cipher.md, or bot/knowledge-econ.md, then rebuild.
module.exports = { SYSTEM_PROMPT: ${JSON.stringify(system)} };
`;

fs.writeFileSync(path.join(__dirname, '..', 'api', '_knowledge.js'), out);
console.log(
  `api/_knowledge.js written: ${(system.length / 1024).toFixed(1)} KB system prompt ` +
  `(~${Math.round(system.length / 4).toLocaleString()} tokens)`
);
